/**
 * Universal safe translation function with cascade fallbacks:
 * Selected Language -> English -> Raw Key (never crashes or shows missing key variable)
 */
export function t(key: string, lang: Language, params?: Record<string, string>): string {
  let result = '';
  if (translations[lang] && translations[lang][key]) {
    result = translations[lang][key];
  } else if (translations.en && translations.en[key]) {
    result = translations.en[key]; // Safe fallback to English
  } else {
    result = key; // Clean fallback
  }

  if (params) {
    Object.keys(params).forEach((paramKey) => {
      result = result.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), params[paramKey]);
    });
  }
  return result;
}

/**
 * Helper to extract localized string from dynamic simulation entity objects
 * E.g., checks object.nameZu, object.nameXh, object.nameAf, etc., falling back to object.name (English)
 */
export function getLocalizedText(entity: any, fieldName: string, lang: Language): string {
  if (!entity) return '';

  const suffixMap: Record<Language, string> = {
    en: '',
    zu: 'Zu',
    xh: 'Xh',
    af: 'Af',
    nso: 'Nso',
    tn: 'Tn',
    st: 'St',
    ts: 'Ts',
    ss: 'Ss',
    ven: 'Ven',
    nr: 'Nr',
    sasl: 'Sasl',
  };

  const suffix = suffixMap[lang];
  if (suffix) {
    const langKey = `${fieldName}${suffix}`;
    if (entity[langKey] && typeof entity[langKey] === 'string' && entity[langKey].trim().length > 0) {
      return entity[langKey];
    }
  }

  // Fallback to English property
  if (entity[fieldName] && typeof entity[fieldName] === 'string') {
    return entity[fieldName];
  }

  return '';
}
